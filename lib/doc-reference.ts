// lib/doc-reference.ts — ΚΑΘΑΡΟ (χωρίς prisma / δίκτυο / server-only).
//
// Μία κανονικοποίηση για τη σύγκριση αναφορών παραστατικών, και ΜΟΝΟ μία: τη χρησιμοποιούν ο
// μεταφραστής του payload (`lib/ocr/purdoc-payload.ts`), ο έλεγχος διπλοεγγραφής (`lib/softone.ts`)
// και η επαλήθευση μετά την εγγραφή (`lib/ocr/post-softone.ts`). Τρία αντίγραφα του ίδιου regex
// θα απέκλιναν την πρώτη φορά που κάποιος διόρθωνε το ένα.

/**
 * ΕΛΛΗΝΙΚΑ ΚΕΦΑΛΑΙΑ ΠΟΥ ΜΟΙΑΖΟΥΝ ΜΕ ΛΑΤΙΝΙΚΑ — και είναι ΔΙΑΦΟΡΕΤΙΚΟΙ χαρακτήρες για τον
 * υπολογιστή. Δεν είναι θεωρητικό: το παραστατικό FINDOC 1042 του πελάτη είναι κυριολεκτικά
 * `ΤΙΜ-AA-2455`, όπου το «ΤΙΜ» είναι ΕΛΛΗΝΙΚΟ (U+03A4 U+0399 U+039C) και το «AA» ΛΑΤΙΝΙΚΟ
 * (U+0041) — μέσα στο ίδιο string. Ένα μοντέλο όρασης που θα διάβαζε τη σειρά με ελληνικό «Α» και
 * τον αριθμό με λατινικό «A» θα έσπαγε κάθε σύγκριση: το πρόθεμα δεν θα αναγνωριζόταν μέσα στον
 * αριθμό (και θα γραφόταν διπλό), και ο έλεγχος διπλοεγγραφής δεν θα έβρισκε την υπάρχουσα γραμμή.
 * Ό,τι φαίνεται ίδιο, συγκρίνεται ίδιο.
 */
const HOMOGLYPHS: Record<string, string> = {
  Α: 'A', Β: 'B', Ε: 'E', Ζ: 'Z', Η: 'H', Ι: 'I', Κ: 'K',
  Μ: 'M', Ν: 'N', Ο: 'O', Ρ: 'P', Τ: 'T', Υ: 'Y', Χ: 'X',
};

/** Τονισμένα κεφαλαία → άτονα, ΠΡΙΝ τα ομόγλυφα: αλλιώς το «Ά» θα πεταγόταν ως διαχωριστικό. */
const ACCENTS: Record<string, string> = {
  Ά: 'Α', Έ: 'Ε', Ή: 'Η', Ί: 'Ι', Ό: 'Ο', Ύ: 'Υ', Ώ: 'Ω', Ϊ: 'Ι', Ϋ: 'Υ',
};

/**
 * Αναφορά παραστατικού → μορφή σύγκρισης: κεφαλαία, χωρίς τόνους, με τα ελληνικά ομόγλυφα
 * διπλωμένα σε λατινικά, και ΧΩΡΙΣ διαχωριστικά — «ΤΠΥ 17» = «ΤΠΥ-17» = «ΤΠΥ/17» = «TΠY17».
 * Τα ελληνικά γράμματα ΧΩΡΙΣ λατινικό ομόγλυφο (Δ, Π, Λ, Φ, Ψ, Ω, Γ, Ξ, Σ, Θ) μένουν ως έχουν.
 */
export function normalizeDocRef(value: unknown): string {
  const up = String(value ?? '').toUpperCase();
  let out = '';
  for (const ch of up) {
    const c = HOMOGLYPHS[ACCENTS[ch] ?? ch] ?? ACCENTS[ch] ?? ch;
    if (/[0-9A-ZΑ-Ω]/.test(c)) out += c;
  }
  return out;
}
