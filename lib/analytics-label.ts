// lib/analytics-label.ts — ΚΑΘΑΡΟ (χωρίς React / prisma / δίκτυο).
//
// Η ετικέτα μιας τιμής αναλυτικής (κέντρο κόστους, **έργο**, κατηγορία δραστηριότητας) χτίζεται
// παντού ως `«ΚΩΔΙΚΟΣ — Τίτλος»` — και στον client όταν διαλέγει ο χρήστης, και στον server όταν
// ξαναφορτώνεται αποθηκευμένη τιμή.
//
// ΤΟ ΠΡΟΒΛΗΜΑ ΠΟΥ ΛΥΝΕΙ. Το combobox έδειχνε αυτή τη συμβολοσειρά σε **μία γραμμή με `truncate`},
// μέσα σε πλαίσιο που μοιράζεται με την ένδειξη προέλευσης και το κουμπί καθαρισμού. Στον
// επιμερισμό, όπου τα πεδία μπαίνουν δύο-δύο σε στήλη, το πλάτος δεν φτάνει: κόβεται ό,τι είναι
// δεξιά, δηλαδή **ακριβώς ο τίτλος** — και ο χρήστης βλέπει μόνο έναν κωδικό που δεν του λέει
// τίποτα. Χωρίζοντάς τα, ο τίτλος παίρνει τη δική του γραμμή και προηγείται· ο κωδικός από κάτω.

export interface AnalyticsParts {
  /** Ο κωδικός, αν η ετικέτα τον κουβαλά. */
  code: string | null;
  /** Ο τίτλος — ό,τι μένει μετά τον πρώτο διαχωριστή. Ποτέ κενό αν υπάρχει κείμενο. */
  title: string;
}

/** Ο διαχωριστής που βάζουμε ΕΜΕΙΣ όταν χτίζουμε την ετικέτα. */
const SEP = ' — ';

/**
 * Χωρίζει «ΚΩΔΙΚΟΣ — Τίτλος» σε κωδικό και τίτλο.
 *
 * Σπάει στον **πρώτο** διαχωριστή μόνο: ο τίτλος μπορεί κάλλιστα να περιέχει παύλα («Ανακαίνιση —
 * Β' φάση») και δεν επιτρέπεται να κοπεί στη μέση. Ετικέτα χωρίς διαχωριστή (παλιά δεδομένα, ή
 * σκέτο id) επιστρέφεται ΟΛΗ ως τίτλος: καλύτερα να δει ο χρήστης κάτι παρά κενό.
 */
export function analyticsParts(label: string | null | undefined): AnalyticsParts {
  // Κρέμεται διαχωριστής στο τέλος («ΕΡΓ003 — ») όταν το όνομα ήρθε κενό από το μητρώο. Φεύγει
  // εδώ, αλλιώς θα τυπωνόταν στην οθόνη ως «ΕΡΓ003 —».
  const s = String(label ?? '').trim().replace(/\s*—\s*$/, '').trim();
  if (!s) return { code: null, title: '' };
  const i = s.indexOf(SEP);
  if (i <= 0) return { code: null, title: s };
  const code = s.slice(0, i).trim();
  const title = s.slice(i + SEP.length).trim();
  return title ? { code: code || null, title } : { code: null, title: code || s };
}

/** Η ετικέτα όπως τη χτίζουμε παντού — ένα σημείο, για να μη διαφωνήσουν client και server. */
export const analyticsLabel = (code: string, name: string): string => `${code}${SEP}${name}`;
