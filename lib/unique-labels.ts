/**
 * Ετικέτες επιλογών που **ξεχωρίζουν** μεταξύ τους.
 *
 * Γιατί υπάρχει: τα μητρώα του SoftOne επιτρέπουν δύο γραμμές με **ίδια περιγραφή** και
 * διαφορετικό κωδικό — π.χ. δύο «Μηδενικός Συντελεστής ΦΠΑ 0%» στις κατηγορίες ΦΠΑ. Σε ένα
 * `<select>` αυτό είναι τυφλή επιλογή: ο χρήστης βλέπει δύο ταυτόσημες γραμμές και δεν έχει
 * κανέναν τρόπο να καταλάβει ποια είναι ποια.
 *
 * Η λύση δεν είναι να κολλήσουμε τον κωδικό σε ΟΛΕΣ τις ετικέτες (θόρυβος σε κάθε λίστα), αλλά
 * **μόνο σε όσες επαναλαμβάνονται**. Μια μοναδική ετικέτα μένει καθαρή.
 */

export interface LabelledOption {
  code: string;
  label: string;
}

/** Κανονικοποίηση για τη σύγκριση: κεφαλαία, χωρίς πολλαπλά κενά. */
const norm = (s: string) => String(s ?? '').trim().replace(/\s+/g, ' ').toUpperCase();

/**
 * Επιστρέφει τις ίδιες επιλογές, με τον **κωδικό σε παρένθεση** μόνο σε όσες μοιράζονται
 * ετικέτα με κάποια άλλη. Η σειρά διατηρείται και ο `code` δεν αλλάζει ποτέ — είναι η τιμή που
 * φεύγει στο SoftOne.
 */
export function disambiguateLabels<T extends LabelledOption>(options: readonly T[]): T[] {
  const count = new Map<string, number>();
  for (const o of options) {
    const k = norm(o.label);
    count.set(k, (count.get(k) ?? 0) + 1);
  }
  return options.map((o) => {
    const k = norm(o.label);
    if ((count.get(k) ?? 0) < 2) return o;
    // ΚΑΜΙΑ εξυπνάδα «ο κωδικός φαίνεται ήδη μέσα στην ετικέτα»: οι κωδικοί εδώ είναι συχνά
    // μονοψήφιοι («0», «1»), οπότε ένα `includes` πετυχαίνει τυχαία μέσα σε «… 0%» και αφήνει
    // τη ΜΙΑ από τις δύο διπλές ετικέτες χωρίς κωδικό — δηλαδή πάλι αδιάκριτες. Μια μικρή
    // επανάληψη είναι ασήμαντη μπροστά σε δύο ταυτόσημες επιλογές.
    return { ...o, label: `${o.label} · κωδ. ${o.code}` };
  });
}
