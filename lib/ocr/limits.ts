// lib/ocr/limits.ts — ISOMORPHIC, ΚΑΘΑΡΟ. Τα όρια μεγέθους αρχείου του OCR, σε ΕΝΑ μέρος.
//
// Υπάρχει γιατί ο αριθμός που ΔΙΑΒΑΖΕΙ ο χρήστης στην περιοχή drop και ο αριθμός που ΕΠΙΒΑΛΛΕΙ ο
// server ήταν δύο διαφορετικές σταθερές σε δύο αρχεία — και απέκλιναν (η οθόνη έλεγε 25 MB, ο
// διαχωρισμός δεχόταν 60). Ένα ψέμα στη διεπαφή δεν είναι μικρό: ο χρήστης είτε δεν δοκιμάζει
// αρχείο που θα περνούσε, είτε περιμένει ένα ανέβασμα που θα απορριφθεί στο τέλος.
//
// Το κείμενο της οθόνης, ο έλεγχος του route και το μήνυμα λάθους διαβάζουν ΟΛΑ από εδώ.

/** Μεμονωμένο παραστατικό (εικόνα ή PDF) — μία σελίδα ή λίγες. */
export const MAX_OCR_BYTES = 25 * 1024 * 1024;

/**
 * Πολυ-παραστατικό PDF προς διαχωρισμό. Πολύ μεγαλύτερο επίτηδες: μια σαρωμένη στοίβα ημέρας
 * είναι δεκάδες σελίδες εικόνας, και τα 25 MB του μεμονωμένου αρχείου την έκοβαν άδικα.
 */
export const MAX_SPLIT_BYTES = 100 * 1024 * 1024;

const mb = (bytes: number) => Math.round(bytes / (1024 * 1024));

/** Τα ίδια όρια σε MB, για τα κείμενα της διεπαφής και τα μηνύματα λάθους. */
export const MAX_OCR_MB = mb(MAX_OCR_BYTES);
export const MAX_SPLIT_MB = mb(MAX_SPLIT_BYTES);
