/**
 * **Ποιοι τύποι καρτέλας προσφέρονται ως ενέργεια** σε έναν εκδότη της ουράς «Νέοι
 * συναλλασσόμενοι» — καθαρή λογική, χωρίς Prisma και χωρίς `server-only`, ώστε να τη
 * μοιράζονται το client panel και τα tests.
 *
 * Στο SoftOne η ίδια εταιρεία είναι **ξεχωριστή γραμμή `TRDR` ανά τύπο**: προμηθευτής (12),
 * πιστωτής (16), χρεώστης (15) — ίδιο ΑΦΜ, διαφορετικό `TRDR`, διαφορετικός κωδικός. Μέχρι
 * τώρα το panel πρόσφερε κουμπί δημιουργίας ΜΟΝΟ για τύπο που κάποιο εκκρεμές παραστατικό
 * απαιτούσε (`group.missing`). Ο λογιστής όμως ξέρει συχνά από πριν ότι ο ίδιος εκδότης θα
 * εμφανιστεί και ως πιστωτής ή χρεώστης, και δεν είχε τρόπο να το πει χωρίς να περιμένει
 * παραστατικό που θα το επιβάλει.
 *
 * Οι δύο καταστάσεις **δεν** ισοπεδώνονται:
 *  • **απαιτούμενος** τύπος = εκκρεμότητα με λόγο και πλήθος παραστατικών (κίτρινη γραμμή)·
 *  • **διαθέσιμος προς προσθήκη** τύπος = απλή δευτερεύουσα ενέργεια, χωρίς προειδοποίηση.
 *
 * Τύπος που **έχει ήδη καρτέλα** δεν προσφέρεται ποτέ — φαίνεται στη λίστα «Καρτέλες στο
 * SoftOne» από πάνω.
 *
 * Ο **πελάτης** (`SODTYPE` 13) είναι εκτός: η εφαρμογή καταχωρεί μόνο εισερχόμενα
 * παραστατικά, ποτέ πωλήσεις — γι' αυτό δεν είναι καν μέλος του {@link TraderKind}.
 */

/** Συναλλασσόμενος που εκδίδει παραστατικό προς εμάς. Ίδιος τύπος με το `lib/softone.ts`. */
export type TraderKind = 'supplier' | 'creditor' | 'debtor';

/** Σειρά εμφάνισης — η ίδια με τα radio της φόρμας, ώστε να μη «χοροπηδά» το UI. */
export const TRADER_KINDS: readonly TraderKind[] = ['supplier', 'creditor', 'debtor'];

/** Ό,τι χρειάζεται η απόφαση από μια υπάρχουσα καρτέλα — τίποτα άλλο. */
export interface TraderKindCardRef {
  /** `null` = `SODTYPE` εκτός των τριών (π.χ. πελάτης 13): δεν καλύπτει κανέναν τύπο εδώ. */
  kind: TraderKind | null;
}

/** Ό,τι χρειάζεται η απόφαση από έναν απαιτούμενο τύπο. */
export interface TraderKindNeedRef {
  kind: TraderKind;
}

export interface TraderKindPresence {
  /** Οι καρτέλες που ΥΠΑΡΧΟΥΝ ήδη στο SoftOne για αυτό το ΑΦΜ. */
  cards: readonly TraderKindCardRef[];
  /** Οι τύποι που ΑΠΑΙΤΟΥΝ τα εκκρεμή παραστατικά και λείπουν (η κίτρινη γραμμή). */
  missing: readonly TraderKindNeedRef[];
}

/** `true` όταν το ΑΦΜ έχει ήδη καρτέλα αυτού του τύπου. */
export function hasTraderCard(cards: readonly TraderKindCardRef[], kind: TraderKind): boolean {
  return cards.some((c) => c.kind === kind);
}

/**
 * Οι τύποι που προσφέρονται ως **απλή προσθήκη**: ούτε έχουν καρτέλα, ούτε τους ζητά ήδη
 * κάποιο παραστατικό.
 *
 * Ο αποκλεισμός των απαιτούμενων δεν είναι λεπτομέρεια εμφάνισης: αν ο ίδιος τύπος έβγαινε και
 * ως κίτρινη προειδοποίηση και ως ουδέτερο κουμπί, το UI θα έλεγε δύο φορές το ίδιο πράγμα με
 * δύο διαφορετικούς βαθμούς επείγοντος. Η προειδοποίηση κρατά το δικό της κουμπί.
 */
export function addableTraderKinds({ cards, missing }: TraderKindPresence): TraderKind[] {
  const required = new Set<TraderKind>(missing.map((m) => m.kind));
  return TRADER_KINDS.filter((k) => !hasTraderCard(cards, k) && !required.has(k));
}

/**
 * **Τι θα συμβεί στα παραστατικά άγνωστης σειράς** όταν πατηθεί «Δημιουργία στο SoftOne» —
 * σε μία ελληνική πρόταση. `null` όταν δεν υπάρχει κανένα (τότε δεν λέγεται τίποτα).
 *
 * Το `applyTraderToDocs` δίνει σε κάθε εκκρεμές παραστατικό την καρτέλα που ζητά **η σειρά
 * του**· όποιο δεν έχει αναγνωρισμένη σειρά δεν ζητά τίποτα, οπότε παίρνει την καρτέλα που
 * μόλις δημιουργήθηκε — όποιου τύπου κι αν είναι αυτή. Όσο η δημιουργία γινόταν μόνο για τύπο
 * που ΑΠΑΙΤΟΥΣΕ κάποιο παραστατικό, αυτό ήταν αθώο. Από τη στιγμή που ο χρήστης μπορεί να
 * προσθέσει τύπο **με δική του πρωτοβουλία**, η συνέπεια πρέπει να είναι γραμμένη πριν το
 * κλικ, όχι να ανακαλύπτεται μετά.
 */
export function unknownSeriesLinkNotice(count: number): string | null {
  if (!Number.isFinite(count) || count < 1) return null;
  return count === 1
    ? 'Θα συνδεθεί και 1 παραστατικό άγνωστης σειράς σε αυτή την καρτέλα.'
    : `Θα συνδεθούν και ${count} παραστατικά άγνωστης σειράς σε αυτή την καρτέλα.`;
}
