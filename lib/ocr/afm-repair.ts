// lib/ocr/afm-repair.ts — ΚΑΘΑΡΟ (χωρίς prisma / δίκτυο).
//
// ΥΠΟΨΗΦΙΑ ΣΩΣΤΑ ΑΦΜ για ένα ΑΦΜ που διαβάστηκε λάθος, και σύγκριση επωνυμιών.
//
// ΓΙΑΤΙ. Ένα πραγματικό παραστατικό έχει ΠΑΝΤΑ ΑΦΜ που περνά τον έλεγχο ψηφίου — άρα όταν δεν
// περνά, το λάθος είναι της ανάγνωσης, όχι του χαρτιού. Μετρημένα στα δεδομένα της ουράς:
//   «999867881» αντί για «999863881» (Entersoft) — ένα 3 διαβάστηκε 7
//   «09401924»  αντί για «094019245» (ΟΤΕ)      — χάθηκε το τελευταίο ψηφίο
//
// Ο έλεγχος mod-11 αφήνει περίπου ΕΝΑ στα ΔΕΚΑ τυχαία 9ψήφια να περάσουν. Άρα ένα ΑΦΜ που
// «περνά» ΔΕΝ είναι σωστό — είναι υποψήφιο. Γι' αυτό τίποτα από εδώ δεν γράφεται μόνο του: κάθε
// υποψήφιο πρέπει να επιβεβαιωθεί από την ΑΑΔΕ με επωνυμία που ταιριάζει (`afm-recovery.ts`).
import { isValidAfm } from '@/lib/ocr/validate';
import { foldGreek } from '@/lib/ocr/search-match';

/**
 * Ζεύγη ψηφίων που το OCR μπερδεύει συχνά — ΠΡΩΤΑ αυτά, γιατί είναι τα πιθανότερα. Μια τυχαία
 * αντικατάσταση (π.χ. 2→9) δοκιμάζεται μόνο αφού εξαντληθούν αυτές.
 */
const CONFUSABLE: Record<string, string[]> = {
  '0': ['8', '6', '9', '3'], '1': ['7', '4'], '2': ['7', '3'], '3': ['8', '5', '9', '2'],
  '4': ['1', '9'], '5': ['6', '3', '8'], '6': ['5', '8', '0'], '7': ['1', '2'],
  '8': ['3', '0', '6', '9', '5'], '9': ['4', '0', '8', '3'],
};

/**
 * Υποψήφια σωστά ΑΦΜ, από το πιθανότερο προς το λιγότερο πιθανό, ΜΟΝΟ όσα περνούν τον έλεγχο.
 *
 *   9 ψηφία  → μία αντικατάσταση (πρώτα οι συγχύσεις του OCR) ή αντιμετάθεση γειτονικών
 *   8 ψηφία  → ένα ψηφίο έλειψε: παρεμβολή σε κάθε θέση
 *   10 ψηφία → ένα ψηφίο περίσσεψε: αφαίρεση από κάθε θέση
 *
 * `limit`: κάθε υποψήφιο κοστίζει μια κλήση στην ΑΑΔΕ — ένα πλαφόν κρατά το κόστος φραγμένο.
 */
export function afmRepairCandidates(bad: string, limit = 12): string[] {
  const d = String(bad ?? '').replace(/\D+/g, '');
  const out: string[] = [];
  const seen = new Set<string>();
  const push = (c: string) => {
    if (c.length === 9 && c !== d && !seen.has(c) && isValidAfm(c)) { seen.add(c); out.push(c); }
  };

  if (d.length === 9) {
    // 1. Συγχύσεις του OCR.
    for (let i = 0; i < 9; i++) for (const r of CONFUSABLE[d[i]] ?? []) push(d.slice(0, i) + r + d.slice(i + 1));
    // 2. Αντιμετάθεση γειτονικών.
    for (let i = 0; i < 8; i++) push(d.slice(0, i) + d[i + 1] + d[i] + d.slice(i + 2));
    // 3. Οποιαδήποτε άλλη αντικατάσταση.
    for (let i = 0; i < 9; i++) for (let k = 0; k <= 9; k++) push(d.slice(0, i) + k + d.slice(i + 1));
  } else if (d.length === 8) {
    // Το πιο συνηθισμένο: χάνεται το ΤΕΛΕΥΤΑΙΟ ψηφίο (κομμένο περιθώριο) — πρώτα αυτό.
    for (let k = 0; k <= 9; k++) push(d + k);
    for (let i = 0; i < 8; i++) for (let k = 0; k <= 9; k++) push(d.slice(0, i) + k + d.slice(i));
  } else if (d.length === 10) {
    for (let i = 0; i < 10; i++) push(d.slice(0, i) + d.slice(i + 1));
  }
  return out.slice(0, limit);
}

/** Λέξεις νομικής μορφής — δεν ξεχωρίζουν μια εταιρεία από άλλη, άρα δεν μετράνε στη σύγκριση. */
const LEGAL_WORDS = new Set([
  'αε', 'ανωνυμη', 'ανωνυμοσ', 'εταιρεια', 'εταιρια', 'μονοπροσωπη', 'επε', 'ικε', 'οε', 'εε',
  'μικε', 'αεβε', 'αβεε', 'αβετε', 'αεβευ', 'εμπορικη', 'βιομηχανικη', 'και', 'σια', 'τησ', 'του', 'των',
  'ltd', 'limited', 'sa', 'ae', 'co', 'inc', 'llc', 'gmbh', 'srl', 'spa', 'bv', 'ag', 'kg',
]);

/** Οι λέξεις που ΤΑΥΤΟΠΟΙΟΥΝ μια επωνυμία: χωρίς τόνους, χωρίς στίξη, χωρίς νομική μορφή. */
export function nameTokens(name: string | null | undefined): Set<string> {
  const folded = foldGreek(String(name ?? ''))
    .replace(/(\p{L})\.(?=\p{L}\.)/gu, '$1')   // «α.ε.» → «αε.»: οι συντομογραφίες με τελείες ενώνονται
    .replace(/[^\p{L}\p{N}]+/gu, ' ');
  return new Set(folded.split(' ').filter((t) => t.length >= 2 && !LEGAL_WORDS.has(t)));
}

/**
 * Ταιριάζουν δύο επωνυμίες; Αυστηρά ΑΡΚΕΤΑ ώστε ένα τυχαίο ΑΦΜ που περνά τον έλεγχο να ΜΗΝ
 * γίνει δεκτό επειδή μοιράζεται τη λέξη «ΣΥΣΤΗΜΑΤΑ», και χαλαρά αρκετά ώστε «Α.Ε.» και
 * «ΑΝΩΝΥΜΗ ΕΤΑΙΡΕΙΑ» να μη χαλάνε τη σύγκριση.
 *
 * Κανόνας, ΔΥΟ σκέλη:
 *   1. τουλάχιστον τα μισά ταυτοποιητικά tokens της ΜΙΚΡΟΤΕΡΗΣ επωνυμίας υπάρχουν στη μεγαλύτερη·
 *   2. η ΠΡΩΤΗ χαρακτηριστική λέξη μιας από τις δύο υπάρχει στην άλλη.
 *
 * Το (2) μπήκε επειδή το (1) μόνο του απέτυχε σε πραγματικό ζεύγος: «INGENIO ΣΥΣΤΗΜΑΤΑ
 * ΠΛΗΡΟΦΟΡΙΚΗΣ» και «ΚΑΡΑΦΥΛΛΗΣ ΣΥΣΤΗΜΑΤΑ ΠΛΗΡΟΦΟΡΙΚΗΣ» μοιράζονται τις δύο από τις τρεις λέξεις
 * — τις ΓΕΝΙΚΕΣ. Αυτό που ξεχωρίζει μια εταιρεία είναι το όνομά της, και αυτό έρχεται σχεδόν
 * πάντα πρώτο (η νομική μορφή έχει ήδη αφαιρεθεί, όπου κι αν ήταν).
 */
export function namesMatch(a: string | null | undefined, b: string | null | undefined): boolean {
  const A = nameTokens(a), B = nameTokens(b);
  if (A.size === 0 || B.size === 0) return false;
  const [small, big] = A.size <= B.size ? [A, B] : [B, A];
  const common = [...small].filter((t) => big.has(t));
  const firstA = [...A][0], firstB = [...B][0];
  return common.length * 2 >= small.size && (B.has(firstA) || A.has(firstB));
}
