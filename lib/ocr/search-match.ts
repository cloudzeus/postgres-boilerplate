// ΓΙΑΤΙ Η ΑΝΑΖΗΤΗΣΗ ΛΟΓΑΡΙΑΣΜΩΝ ΔΕΝ ΕΒΡΙΣΚΕ ΤΙΠΟΤΑ.
//
// Το `mode: 'insensitive'` της Prisma είναι `ILIKE`: αγνοεί πεζά/κεφαλαία, ΟΧΙ τόνους. Ο χρήστης
// γράφει «ΚΙΝΗΣ» — κανείς δεν βάζει τόνους σε αναζήτηση — και η βάση έχει «Έξοδα Κίνησης».
// Μετρημένο πριν τη διόρθωση: «ΚΙΝΗΣ» → 0 αποτελέσματα, ενώ ο λογαριασμός υπάρχει.
//
// Το ίδιο και ο ΚΩΔΙΚΟΣ: «6400» → 0, «64.00» → 6. Ο λογαριασμός γράφεται «64.00.23» και κανείς
// δεν πληκτρολογεί τις τελείες.
//
// Τα μητρώα είναι μικρά (207 χρεοπιστώσεις, 542 λογαριασμοί εσόδων/εξόδων), οπότε το φιλτράρισμα
// γίνεται στη μνήμη — καμία μετανάστευση, καμία επέκταση `unaccent` στη βάση.

/**
 * Κανονικοποίηση ελληνικού κειμένου για σύγκριση.
 *
 * Η ΣΕΙΡΑ ΕΧΕΙ ΣΗΜΑΣΙΑ: το `toLowerCase()` ΠΑΡΑΓΕΙ τελικό σίγμα όταν το «Σ» είναι στο τέλος
 * («ΚΙΝΗΣ» → «κινης», U+03C2), οπότε η αντικατάσταση `ς → σ` πρέπει να ΕΠΕΤΑΙ. Με την αντίστροφη
 * σειρά, κάθε αναζήτηση με ΚΕΦΑΛΑΙΑ που τελειώνει σε «Σ» αποτυγχάνει σιωπηλά.
 */
export const foldGreek = (v: string): string =>
  v.normalize('NFD').replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/ς/g, 'σ');

/** Ο κωδικός συγκρίνεται ΧΩΡΙΣ διαχωριστικά: «6400» βρίσκει το «64.00.23». */
export const foldCode = (v: string): string => v.replace(/[^0-9a-zA-Z]/g, '').toLowerCase();

/**
 * Ταιριάζει το ερώτημα σε κωδικό Ή περιγραφή, ανεκτικά σε τόνους, πεζά/κεφαλαία και τελείες.
 * Κενό ερώτημα ⇒ `true`: η λίστα ανοίγει ολόκληρη, δεν απαιτεί να μαντέψεις τα πρώτα γράμματα.
 */
export function matchesQuery(q: string, code: string | null, name: string | null): boolean {
  const needle = foldGreek(q.trim());
  if (!needle) return true;
  if (foldGreek(name ?? '').includes(needle)) return true;
  const c = foldCode(q);
  return c.length > 0 && foldCode(code ?? '').includes(c);
}
