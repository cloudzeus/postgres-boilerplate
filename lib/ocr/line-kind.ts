// «Τι ΕΙΔΟΥΣ εγγραφή μητρώου χρειάζεται αυτή η γραμμή;» — είδος, υπηρεσία, έξοδο ή χρεοπίστωση.
//
// Η προηγούμενη απάντηση ήταν σταθερά **`'product'`** όταν δεν υπήρχε τίποτα άλλο. Αυτό δεν ήταν
// προεπιλογή, ήταν **ισχυρισμός**: μια χρέωση cloud της Google και ένα ΨΩΜΙ από ταβέρνα έπαιρναν
// και τα δύο chip «Προϊόν», και ο χρήστης δεν είχε κανέναν τρόπο να ξεχωρίσει «το ξέρω» από «δεν
// ξέρω». Για μια επιχείρηση που σαρώνει ΕΙΣΕΡΧΟΜΕΝΑ τιμολόγια και δεν μεταπωλεί, το `'product'`
// είναι επιπλέον και η χειρότερη δυνατή εικασία: σχεδόν όλα είναι έξοδα ή υπηρεσίες.
//
// Ο κανόνας εδώ είναι ο ίδιος με όλη την εφαρμογή: **χωρίς απόδειξη, καμία δήλωση** — `null`
// («χωρίς κατηγορία»), και ο χρήστης ή το μοντέλο αποφασίζει.

import type { MatchKind } from '@/lib/ocr/line-match';
import type { PostLineTable } from '@/lib/ocr/posting-target';
import { GREEK_LATIN_HOMOGLYPHS } from '@/lib/doc-reference';

/**
 * Ο πίνακας γραμμών του προορισμού ορίζει το μητρώο **μόνο όπου όντως το ορίζει**:
 *
 *  • `LINLINES` ⇒ χρεοπίστωση (`MTRL` 53) και `EXPANAL` ⇒ έξοδο (`EXPN`): δεν είναι εικασία,
 *    είναι η δομή του ERP — άλλο μητρώο δεν χωράει σε αυτούς τους πίνακες.
 *  • `ITELINES` / `SRVLINES` ⇒ **`null`**. Οι δύο πίνακες δέχονται ΚΑΙ οι δύο οποιοδήποτε
 *    `MTRL` (δες `lineFits` στο `lib/ocr/purdoc-payload.ts` και το μήνυμα `lines_need_mtrl`:
 *    «δέχεται μόνο είδη ή υπηρεσίες»). Μια σειρά ρυθμισμένη σε `ITELINES` λέει δηλαδή «είδος ή
 *    υπηρεσία», ΟΧΙ «είδος» — και ένα σίγουρο chip «Προϊόν» πάνω σε υπηρεσία είναι ακριβώς ο
 *    ισχυρισμός που αυτός ο κώδικας υπάρχει για να τον σβήσει.
 *  • `AUTO` (PURDOC «ανά γραμμή») δεν λέει τίποτα: εκεί χωράνε και τα τρία.
 */
export const KIND_FOR_LINE_TABLE: Record<PostLineTable, MatchKind | null> = {
  AUTO: null,
  ITELINES: null,
  SRVLINES: null,
  EXPANAL: 'expense',
  LINLINES: 'lineitem',
};

/**
 * Λέξεις που δηλώνουν **αναμφισβήτητα** υπηρεσία μέσα στην ίδια την περιγραφή της γραμμής.
 *
 * Σκόπιμα ΜΙΚΡΗ λίστα. Δελεαστικές αλλά διφορούμενες λέξεις («ρεύμα», «ενοίκιο», «συνδρομή»,
 * «μεταφορικά») έμειναν ΕΞΩ: στο SoftOne μπορεί κάλλιστα να είναι **έξοδο** (`EXPN`) ή
 * **χρεοπίστωση** αντί για υπηρεσία (`MTRL` 52), και ένα λάθος chip με σιγουριά είναι χειρότερο
 * από ένα κενό. Ό,τι δεν πιάνεται εδώ πάει στο μοντέλο ή στον χρήστη.
 */
const SERVICE_WORDS = [
  'υπηρεσι', 'υπηρεσία', 'παροχη υπηρεσιων', 'service', 'services',
];

/**
 * Κανονικοποίηση για τη σύγκριση λέξεων: χωρίς τόνους, με τα **ελληνικά ομόγλυφα** διπλωμένα σε
 * λατινικά, πεζά.
 *
 * Τα ομόγλυφα δεν είναι θεωρητικά εδώ. Οι περιγραφές γραμμών βγαίνουν από τον ΙΔΙΟ αγωγό OCR
 * που μας έδωσε το `ΤΙΜ-AA-2455` με ελληνικό «ΤΙΜ» και λατινικό «AA» μέσα στο ίδιο string (δες
 * `lib/doc-reference.ts`). Ένα «ΥΠΗΡΕΣΙΑ» γραμμένο με λατινικά Υ/Ρ/Ε/Η είναι για τον υπολογιστή
 * άλλη λέξη, και θα ξέφευγε σιωπηλά από τον έλεγχο — δηλαδή θα έχανε η ΜΟΝΗ γλωσσική ένδειξη
 * που έχουμε. Ο πίνακας είναι ο ίδιος, εξαγμένος, όχι αντίγραφο.
 *
 * Η σειρά έχει σημασία: **τόνοι πρώτα, ομόγλυφα μετά**. Ανάποδα, το «Ί» δεν θα ταίριαζε στο
 * `Ι → I` και θα κατέληγε «ι» ενώ το άτονο «Ι» θα κατέληγε «i» — δύο διαφορετικές λέξεις.
 */
const fold = (s: string): string => {
  const up = String(s ?? '').toUpperCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
  let out = '';
  for (const ch of up) out += GREEK_LATIN_HOMOGLYPHS[ch] ?? ch;
  return out.toLowerCase();
};

/** `true` όταν η περιγραφή περιέχει αναμφισβήτητη ένδειξη υπηρεσίας. */
export function looksLikeService(text: string): boolean {
  const t = fold(text);
  return SERVICE_WORDS.some((w) => t.includes(fold(w)));
}

export interface KindEvidence {
  /** Ο τύπος που θυμάται ο κανόνας (`LineMatchRule`) — η ΙΣΧΥΡΟΤΕΡΗ απόδειξη. */
  memoryKind?: MatchKind | null;
  /** `true` όταν κάποια γραμμή της ομάδας έχει ήδη ταιριάξει σε υπηρεσία του SoftOne. */
  matchedService?: boolean;
  /**
   * Οι πίνακες γραμμών των παραστατικών της ομάδας (από τη σειρά του καθενός). Μετρά ΜΟΝΟ όταν
   * συμφωνούν όλοι: μια ομάδα που εμφανίζεται και σε αγορά και σε ειδική συναλλαγή δεν έχει
   * έναν προορισμό, άρα δεν έχει και έναν τύπο.
   *
   * **`null` = άγνωστη σειρά, και μετράει ως ΔΙΑΦΩΝΙΑ.** Ένα παραστατικό του οποίου δεν ξέρουμε
   * πού καταχωρείται δεν είναι παραστατικό που «συμφωνεί»: αν το αγνοούσαμε, ένα γνωστό ανάμεσα
   * σε τέσσερα άγνωστα θα αποφάσιζε για όλη την ομάδα.
   */
  lineTables?: (PostLineTable | null)[];
  /** Η περιγραφή-δείγμα της ομάδας, για τον τελευταίο, συντηρητικό έλεγχο λέξεων. */
  sample?: string | null;
}

/**
 * Ο τύπος της ομάδας από ΝΤΕΤΕΡΜΙΝΙΣΤΙΚΕΣ ενδείξεις, με φθίνουσα ισχύ:
 *
 *  1. **Μνήμη** (`LineMatchRule`) — ο χρήστης το έχει ήδη αποφασίσει μία φορά.
 *  2. **Ήδη ταιριασμένη υπηρεσία** σε κάποια γραμμή της ομάδας.
 *  3. **Ο προορισμός της σειράς** (`LINLINES` → χρεοπίστωση, `EXPANAL` → έξοδο) — δομή του ERP,
 *     όχι εικασία. Μόνο όταν ΟΛΑ τα παραστατικά της ομάδας έχουν **γνωστή** σειρά και
 *     συμφωνούν· έστω και ένα άγνωστο (`null`) αρκεί για να απόσχει ο κανόνας.
 *  4. **Αναμφισβήτητη λέξη υπηρεσίας** στην περιγραφή.
 *
 * Οτιδήποτε άλλο: `null` — «χωρίς κατηγορία».
 *
 * ⚠️ **ΓΙΑΤΙ Η ΚΑΡΤΕΛΑ ΤΟΥ ΕΚΔΟΤΗ ΔΕΝ ΕΙΝΑΙ ΒΑΘΜΙΔΑ ΕΔΩ.**
 *
 * Δοκιμάστηκε και **απορρίφθηκε πάνω σε ζωντανά δεδομένα**. Η ιδέα ήταν: εκδότης με καρτέλα
 * **προμηθευτή** (`TRDR SODTYPE 12`) ⇒ `'product'`. Ακούγεται σωστό — η καρτέλα είναι η σκόπιμη
 * ταξινόμηση του λογιστή και όντως ξεχωρίζει το εμπόρευμα (ΕΛΠ ομάδα 2) από τη δαπάνη (ομάδα 6).
 * Στην ουρά όμως **1 στις 3 σφραγίδες βγήκε λάθος**: 10 από τις 30 ήταν γραμμές
 * «ΠΡΟΓΡΑΜΜΑ ΑΝΑΒΑΘΜΙΣΗΣ IRIS SN: …» ενός προμηθευτή συστημάτων πληροφορικής — **άδειες
 * λογισμικού ανά serial**, όχι απόθεμα. Ο εκδότης κουβαλά ακριβώς το ίδιο `SODTYPE 12` με τον
 * κατασκευαστή σφιγκτήρων του οποίου κάθε γραμμή **είναι** εμπόρευμα.
 *
 * Το συμπέρασμα είναι γενικό και αξίζει να μείνει γραμμένο: **η καρτέλα είναι ΑΝΑΓΚΑΙΑ, ΟΧΙ
 * ΙΚΑΝΗ**. Λέει «αυτός ο οίκος μας πουλά αγαθά», ποτέ «αυτή η γραμμή είναι αγαθό» — και ό,τι
 * ξεχωρίζει τις δύο περιπτώσεις βρίσκεται στο **κείμενο της γραμμής**, που η καρτέλα δεν το
 * βλέπει. Είναι το ίδιο ακριβώς σφάλμα με τον χάρτη `ITELINES` ⇒ προϊόν: δήλωση τύπου από
 * **υποκατάστατο**. Δεν σώζεται με πλουσιότερο λεξιλόγιο· έτσι φτάσαμε εδώ δύο φορές.
 *
 * Η καρτέλα **δεν πετιέται**: μένει ισχυρή ένδειξη εκεί που μπορεί να συνδυαστεί με το κείμενο,
 * δηλαδή στο **prompt** (`lib/ocr/expense-ai.ts`), όπου το μοντέλο βλέπει και τα δύο μαζί.
 */
export function inferLineKind(ev: KindEvidence): MatchKind | null {
  if (ev.memoryKind) return ev.memoryKind;
  if (ev.matchedService) return 'service';

  // Τα άγνωστα ΔΕΝ πετιούνται: το `null` είναι διαφωνία, όχι σιωπή. Αν τα αφαιρούσαμε πριν τον
  // έλεγχο, ένα γνωστό παραστατικό θα αποφάσιζε για μια ομάδα με τέσσερα άγνωστα.
  const tables = ev.lineTables ?? [];
  const known = tables.filter((t): t is PostLineTable => t != null);
  if (tables.length > 0 && known.length === tables.length) {
    const kinds = new Set(known.map((t) => KIND_FOR_LINE_TABLE[t]));
    if (kinds.size === 1) {
      const only = [...kinds][0];
      if (only) return only;
    }
  }

  if (ev.sample && looksLikeService(ev.sample)) return 'service';
  return null;
}
