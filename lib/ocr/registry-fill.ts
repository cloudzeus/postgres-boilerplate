//
// «Ποια τιμή κερδίζει;» όταν το ίδιο πεδίο έχει δύο πηγές: ό,τι διάβασε το **OCR** από την
// τυπωμένη σελίδα και ό,τι λέει το **μητρώο** (ΑΑΔΕ για ελληνικό ΑΦΜ, VIES για ξένο).
//
// Για ελληνικό ΑΦΜ το μητρώο ΕΙΝΑΙ η αυθεντία: επωνυμία, Δ.Ο.Υ., επάγγελμα, διεύθυνση, Τ.Κ. και
// πόλη ζουν εκεί επίσημα, ενώ η σελίδα είναι μια εκτύπωση που πέρασε από αναγνώριση κειμένου.
// Γι' αυτό το μητρώο εφαρμόζεται **αυτόματα**. Αυτό όμως δεν σημαίνει σιωπηλά:
//
//   ΧΡΗΣΤΗΣ  >  ΜΗΤΡΩΟ (ΑΑΔΕ/VIES)  >  OCR  >  κενό
//
// Ένα πεδίο που άγγιξε ο χρήστης **δεν ξαναγράφεται ποτέ**, και η προέλευση κάθε αυτόματης τιμής
// φαίνεται στο UI με έναν δρόμο επιστροφής στην τιμή του παραστατικού. Μια φόρμα που ξαναγράφει
// σιωπηλά ό,τι έλεγε το χαρτί είναι ακριβώς ο τρόπος με τον οποίο ένα λάθος ΑΦΜ ή μια παλιά
// εγγραφή μητρώου καταλήγει στον ERP χωρίς να το δει κανείς.

/** Από πού κρατά την τιμή του ένα πεδίο της φόρμας. */
export type FieldSource = 'ocr' | 'aade' | 'vies';

/**
 * Τιμή μητρώου → κανονική μορφή. `null` όταν **δεν υπάρχει τιμή**.
 *
 * Το VIES γράφει «---» όταν το κράτος-μέλος κρύβει επωνυμία ή διεύθυνση. Αυτό ΔΕΝ είναι τιμή:
 * αν εφαρμοζόταν κυριολεκτικά, η επωνυμία του συναλλασσομένου θα γινόταν «---» στον ERP. Το
 * route του VIES το μηδενίζει ήδη· το ξανακάνουμε εδώ γιατί ο κανόνας ανήκει στον κανόνα, όχι
 * σε ένα μόνο σημείο της διαδρομής.
 */
export function registryValue(v: unknown): string | null {
  const s = String(v ?? '').replace(/\s+/g, ' ').trim();
  if (!s || /^-+$/.test(s)) return null;
  return s;
}

export interface RegistryFillInput<K extends string> {
  /** Οι τιμές του μητρώου ανά πεδίο. Κενό / «---» / `null` = δεν υπάρχει τιμή. */
  registry: Partial<Record<K, string | null | undefined>>;
  /** Πεδία που έχει ορίσει ΡΗΤΑ ο χρήστης σε αυτή τη συνεδρία — απαραβίαστα. */
  userOwned?: Iterable<K>;
}

export interface RegistryFillResult<K extends string> {
  /** Τι πρέπει να γραφτεί στη φόρμα (μόνο τα πεδία που αλλάζουν). */
  values: Partial<Record<K, string>>;
  /** Ποια πεδία εφαρμόστηκαν — για τη σήμανση προέλευσης στο UI. */
  applied: K[];
  /** Ποια πεδία είχαν τιμή μητρώου αλλά **δεν** γράφτηκαν επειδή τα κατέχει ο χρήστης. */
  skipped: K[];
}

/**
 * Τι θα εφαρμοστεί από το μητρώο, χωρίς να πειραχτεί τίποτα δικό του χρήστη.
 *
 * ΔΕΝ κοιτάζει αν το πεδίο είναι ήδη γεμάτο: η τιμή του OCR **επίτηδες** αντικαθίσταται — αυτό
 * είναι το νόημα του «πάντα εφαρμογή των στοιχείων της ΑΑΔΕ». Ό,τι προστατεύεται είναι μόνο ό,τι
 * έγραψε ή επέλεξε ο ΧΡΗΣΤΗΣ, και αυτό δηλώνεται ρητά στο `userOwned` — ποτέ δεν συμπεραίνεται
 * από σύγκριση τιμών (δύο πηγές μπορεί κάλλιστα να συμφωνούν κατά λέξη).
 *
 * Κενό μητρώο (ΑΦΜ που δεν βρέθηκε, ανενεργό, ή υπηρεσία που δεν απάντησε) ⇒ **τίποτα δεν
 * γράφεται και τίποτα δεν σβήνεται**: οι τιμές του OCR μένουν στη θέση τους.
 */
export function planRegistryFill<K extends string>(
  input: RegistryFillInput<K>,
): RegistryFillResult<K> {
  const owned = new Set<K>(input.userOwned ?? []);
  const values: Partial<Record<K, string>> = {};
  const applied: K[] = [];
  const skipped: K[] = [];

  for (const key of Object.keys(input.registry) as K[]) {
    const value = registryValue(input.registry[key]);
    if (value == null) continue;
    if (owned.has(key)) { skipped.push(key); continue; }
    values[key] = value;
    applied.push(key);
  }
  return { values, applied, skipped };
}
