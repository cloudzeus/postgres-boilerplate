/**
 * Καθάρισμα διευθύνσεων που το OCR κόλλησε σε μία γραμμή.
 *
 * Αρκετά τιμολόγια (κυρίως ξένα) τυπώνουν τη διεύθυνση σε πολλές γραμμές και ο
 * αναγνώστης τις ενώνει ΧΩΡΙΣ διαχωριστικό: «VelascoClanwilliam PlaceDublin
 * 2Ireland». Έτσι ο geocoder δεν βρίσκει τίποτα. Καθαρή συνάρτηση, χωρίς
 * εξαρτήσεις — χρησιμοποιείται και στον server και στην ουρά.
 */

/** Πεζά (λατινικά + ελληνικά με τόνους) και ψηφία. */
const LOWER = 'a-zα-ωά-ώ';
/** Κεφαλαία (λατινικά + ελληνικά, με τους τονισμένους χαρακτήρες). */
const UPPER = 'A-ZΑ-ΩΆΈΉΊΌΎΏ';

/**
 * Όριο κολλημένων γραμμών: πεζό ή ψηφίο ακριβώς πριν από κεφαλαίο που ΞΕΚΙΝΑΕΙ
 * λέξη (ακολουθείται από πεζό). Το δεύτερο πεζό κρατάει έξω ακρωνύμια και
 * νομικές μορφές τύπου «GmbH», «ΑΕΒΕ», «BV».
 */
const GLUED = new RegExp(`([${LOWER}0-9])([${UPPER}][${LOWER}])`, 'gu');

/**
 * «VelascoClanwilliam PlaceDublin 2Ireland»
 *   → «Velasco, Clanwilliam Place, Dublin 2, Ireland»
 *
 * Διευθύνσεις που έχουν ήδη διαχωριστικά μένουν ως έχουν (πέρα από το μάζεμα
 * διπλών κενών/κομμάτων).
 */
export function splitGluedAddress(s: string): string {
  return String(s ?? '')
    .replace(GLUED, '$1, $2')
    .replace(/\s+/g, ' ')
    .replace(/\s*,\s*/g, ',')
    .replace(/,+/g, ',')
    .replace(/,/g, ', ')
    .replace(/^[\s,]+|[\s,]+$/g, '');
}
