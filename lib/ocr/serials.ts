// lib/ocr/serials.ts — ΚΑΘΑΡΟ. Σειριακοί αριθμοί (S/N) από το κείμενο μιας γραμμής παραστατικού.
//
// ΓΙΑΤΙ ΥΠΑΡΧΕΙ. Οι σειριακοί ζούσαν θαμμένοι μέσα στην περιγραφή («ΠΡΟΓΡΑΜΜΑ ΑΝΑΒΑΘΜΙΣΗΣ IRIS SN:
// DMV24000230-P»): δεν φαίνονταν, δεν αναζητούνταν, και κανείς δεν μπορούσε να απαντήσει «ποιο
// τιμολόγιο αφορά τη μηχανή DMV24000146;». Στα πραγματικά δεδομένα: 11 σειριακοί ταμειακών μηχανών σε
// 4 τιμολόγια του Καραφύλλη — καθένας μια συσκευή πελάτη, δηλαδή η βάση για επανατιμολόγηση,
// εγγύηση και ιστορικό συντήρησης.
//
// ΑΥΣΤΗΡΟ ΣΚΟΠΙΜΑ: σειριακός = ετικέτα (SN, S/N, Serial No, Σ/Ν) + κωδικός που περιέχει ΨΗΦΙΟ. Χωρίς το
// ψηφίο, το «Soft1 OpEn Serial Numbers-Service» θα έβγαζε σειριακό «Numbers-Service».

// ΟΧΙ `\b`: στη JavaScript το `\b` ξέρει μόνο λατινικά, ακόμη και με τη σημαία `u` — το «Σ/Ν» δεν ταίριαζε
// ποτέ. Όρια με Unicode κλάσεις, που αναγνωρίζουν και ελληνικά γράμματα.
const B = '(?<![\\p{L}\\p{N}])';
const E = '(?![\\p{L}\\p{N}])';
const LABEL = new RegExp(
  `(?:${B}S\\s*\\/\\s*N${E}|${B}SN${E}|${B}Serial(?:\\s*(?:No|Number|Nr)\\.?)?|${B}Σ\\s*\\/\\s*Ν${E}|${B}Α\\s*\\/\\s*Α\\s*σειράς)\\s*[:#.\\-]?\\s*`,
  'giu',
);
// ΧΩΡΙΣ τελεία και ΧΩΡΙΣ συνέχεια μετά από κενό: στο «SN: DMV24001420-P.ID: 159894» το «ID» είναι ΑΛΛΟ
// πεδίο της συσκευής. Με την τελεία μέσα, βγαίναν «DMV24001420-P.ID» και «159894» ως σειριακοί.
const TOKEN = /^[A-Z0-9Α-Ω][A-Z0-9Α-Ω\-]{3,}/iu;

/**
 * Οι σειριακοί που αναφέρει ένα κείμενο, με τη σειρά εμφάνισης, χωρίς διπλότυπα. Μετά την ετικέτα
 * δέχεται ΠΟΛΛΟΥΣ κωδικούς χωρισμένους με κόμμα/κάθετο/κενό («SN: A123, A124»).
 */
export function extractSerials(text: string | null | undefined): string[] {
  const s = String(text ?? '');
  const out: string[] = [];
  for (const m of s.matchAll(LABEL)) {
    let rest = s.slice((m.index ?? 0) + m[0].length);
    for (let i = 0; i < 20; i++) {
      const t = TOKEN.exec(rest);
      if (!t) break;
      const code = t[0].replace(/-+$/, '');
      if (/\d/.test(code) && !out.includes(code)) out.push(code);
      rest = rest.slice(t[0].length);
      const sep = /^\s*[,;\/]\s*/u.exec(rest);
      if (!sep) break;
      rest = rest.slice(sep[0].length);
    }
  }
  return out;
}
