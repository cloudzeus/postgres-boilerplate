/**
 * Τιμές ειδών: **χονδρικής** (καθαρή, χωρίς ΦΠΑ) και **λιανικής** (με ΦΠΑ).
 *
 * Γιατί υπάρχει: η τιμή που διαβάζει το OCR σε μια γραμμή **τιμολογίου αγοράς** είναι τιμή
 * **κόστους/χονδρικής** — ό,τι μας χρέωσε ο προμηθευτής, καθαρό. Το SoftOne την περιμένει στο
 * `ITEM.PRICEW` («Χονδρικής»), ΟΧΙ στο `ITEM.PRICER` («Λιανικής»). Και τα δύο πεδία είναι
 * `Float`, `required: false`, `readOnly: false` και — το κρίσιμο — **`calculated: false`**:
 * ο ERP **δεν** υπολογίζει τη λιανική από τη χονδρική, οπότε αν θέλουμε λιανική πρέπει να τη
 * στείλουμε εμείς (επαληθευμένο στο cached schema του object `ITEM`).
 *
 * Το ποσοστό ΦΠΑ έρχεται από την **κατηγορία ΦΠΑ που διάλεξε ο χρήστης στη φόρμα**, όχι από τη
 * γραμμή του τιμολογίου: ο χρήστης μπορεί σκόπιμα να καταχωρήσει το είδος σε άλλο καθεστώς.
 */

/**
 * Σε πόσα δεκαδικά στρογγυλοποιείται η **υπολογισμένη** λιανική.
 *
 * Το schema δηλώνει `decimals: 'P'` — δηλαδή το *προφίλ* δεκαδικών «τιμής» της εγκατάστασης,
 * όχι έναν αριθμό: η ακρίβεια είναι παράμετρος του ERP και ΔΕΝ διαβάζεται από εκεί. Διαλέγουμε
 * **4**: δεν χάνει ποτέ λεπτό (2 δεκαδικά θα άλλαζαν σιωπηλά την τιμή σε εγκατάσταση με
 * μεγαλύτερη ακρίβεια) και ταυτόχρονα κόβει τον θόρυβο του δυαδικού πολλαπλασιασμού
 * (`10 × 1.24 = 12.400000000000002`). Αν η εγκατάσταση κρατά 2, στρογγυλοποιεί το ίδιο το SoftOne.
 *
 * Η **χονδρική** ΔΕΝ στρογγυλοποιείται: είναι αριθμός που έδωσε άνθρωπος ή διάβασε το OCR από
 * το τιμολόγιο — δεν τον «βελτιώνουμε».
 */
export const PRICE_DECIMALS = 4;

/** Στρογγυλοποίηση σε `PRICE_DECIMALS` δεκαδικά, χωρίς τα ψίχουλα του `toFixed` σε string. */
export function roundPrice(value: number, decimals = PRICE_DECIMALS): number {
  if (!Number.isFinite(value)) return 0;
  const f = 10 ** decimals;
  // Το `Number.EPSILON` σπρώχνει τιμές τύπου 1.005 στη σωστή πλευρά της στρογγυλοποίησης.
  return Math.round((value + Number.EPSILON) * f) / f;
}

/**
 * Λιανική από χονδρική και ποσοστό ΦΠΑ: `PRICEW × (1 + rate/100)`.
 *
 * `null` όταν λείπει η τιμή ή **το ποσοστό**: μια κατηγορία χωρίς ποσοστό (π.χ. «Άρθρο 39α»)
 * δεν παράγει λιανική — καλύτερα κανένας αριθμός παρά λάθος αριθμός.
 */
export function retailFromWholesale(
  wholesale: number | null | undefined,
  vatRate: number | null | undefined,
): number | null {
  if (wholesale == null || !Number.isFinite(wholesale)) return null;
  if (vatRate == null || !Number.isFinite(vatRate)) return null;
  return roundPrice(wholesale * (1 + vatRate / 100));
}
